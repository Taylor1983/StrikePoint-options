function generateHistoricalCandles(basePrice: number, count: number, volatility: number): Candle[] {
  const candles: Candle[] = [];
  const totalDays = Math.max(count, 310); // Provide rich historical data for 200-day SMA, 1M, 3M, 6M, 1Y technical analysis
  let curr = basePrice * 0.84;
  const now = new Date();

  for (let i = totalDays; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    // skip weekends
    if (d.getDay() === 0 || d.getDay() === 6) continue;

    const drift = 0.0007; // slight upward drift
    const changePct = (Math.random() - 0.485) * volatility + drift;
    const open = curr;
    const close = Math.max(1, curr * (1 + changePct));
    const high = Math.max(open, close) * (1 + Math.random() * (volatility * 0.5));
    const low = Math.min(open, close) * (1 - Math.random() * (volatility * 0.5));
    const volume = Math.floor(20000000 + Math.random() * 35000000);

    curr = close;

    candles.push({
      time: d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  // Force last candle close to match current price
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }

  return candles;
}

