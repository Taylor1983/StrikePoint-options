/**
 * Generates an authentic options chain around the given ticker and price
 */
export function generateOptionsChainForTicker(
  ticker: Ticker,
  dteDays: number
): ExpirationOptionChain {
  const S = ticker.price;
  const rawBaseIV = ticker.currentIV;
  const T = Math.max(0.001, dteDays / 365);

  // Term Structure adjustment based on IV Rank
  // Low IV Rank (< 50): Contango (front-month IV lower, back-month IV higher)
  // High IV Rank (>= 50): Backwardation (front-month IV elevated, back-month IV lower)
  const isHighVol = ticker.ivRank >= 50;
  const termSpread = isHighVol ? (ticker.ivRank - 50) / 100 : (50 - ticker.ivRank) / 100;
  const termSlope = (dteDays - 30) / 150; // -0.16 at 5D, 0 at 30D, +1.0 at 180D
  const termAdjustment = isHighVol ? -termSlope * termSpread * 0.18 : termSlope * termSpread * 0.18;
  const baseIV = Math.max(0.08, rawBaseIV * (1 + termAdjustment));

  const expDate = new Date();
  expDate.setDate(expDate.getDate() + dteDays);
  const dateStr = expDate.toISOString().split('T')[0];
  const formattedDate = expDate.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
  const monthName = expDate.toLocaleDateString('en-US', { month: 'short' }).toUpperCase();
  const yearShort = expDate.toLocaleDateString('en-US', { year: '2-digit' });
  const monthYear = `${monthName} '${yearShort}`;

  // Determine strike step size based on asset price & type
  let step = 1;
  let strikeCount = 52; // Full institutional strike spectrum (deep OTM to deep ITM)
  if (ticker.symbol === '/6E' || ticker.symbol === '/6C') {
    step = 0.005; // FX 50 pips
  } else if (ticker.symbol === '/NG') {
    step = 0.05;  // Natural Gas $0.05
  } else if (ticker.symbol === '/SI') {
    step = 0.25;  // Silver $0.25
  } else if (ticker.symbol === '/ZB' || ticker.symbol === '/ZN' || ticker.symbol === '/CGB' || ticker.symbol === '/CGF') {
    step = 0.50;  // Treasury & GoC benchmark bonds half-point
  } else if (ticker.symbol === '/CRA') {
    step = 0.125; // 3M CORRA quarter/eighth point
  } else if (ticker.symbol === '/SXF' || ticker.symbol === '/SXM') {
    step = 5;     // S&P/TSX 60 5 index points (strikes: 1445, 1450, 1455, 1460, 1465...)
  } else if (ticker.symbol === '/SCF') {
    step = 50;    // S&P/TSX Composite 50 index points
  } else if (ticker.symbol === '/RTY') {
    step = 10;    // Russell 10 pts
  } else if (S > 50000) {
    step = 500; // e.g. /BTC
  } else if (S > 15000) {
    step = 50;  // e.g. /NQ
  } else if (S > 4000) {
    step = 25;  // e.g. /ES
  } else if (S > 2000) {
    step = 10;  // e.g. /GC, /ETH
  } else if (S > 500) {
    step = 5;
  } else if (S > 200) {
    step = 2.5;
  } else if (S > 100) {
    step = 1;
  } else if (S > 50) {
    step = 1;
  } else {
    step = 0.5;
  }

  const roundedAtm = Math.round(S / step) * step;
  const startStrike = Math.max(step, roundedAtm - Math.floor(strikeCount / 2) * step);

  // DTE scaling for skew steepness: short DTE has steeper skew slope (1 / sqrt(T))
  const dteScale = Math.max(0.55, Math.min(1.65, Math.sqrt(30 / Math.max(5, dteDays))));

  const calls: OptionContract[] = [];
  const puts: OptionContract[] = [];
  const strikePrecision = (ticker.symbol === '/6E' || ticker.symbol === '/6C') ? 4 : (ticker.symbol === '/NG' || ticker.symbol === '/CRA') ? 3 : 2;

  for (let i = 0; i < strikeCount; i++) {
    const strike = Number((startStrike + i * step).toFixed(strikePrecision));
    const moneyness = strike / S; // >1 OTM call, <1 OTM put

    // Realistic volatility smile / skew (lower strikes have higher IV in equities)
    const skewFactor = (1 - moneyness) * (0.34 * dteScale);
    const smileFactor = Math.pow(moneyness - 1, 2) * (0.42 * dteScale);
    const callIV = Math.max(0.06, Number((baseIV + skewFactor * 0.55 + smileFactor).toFixed(4)));
    const putIV = Math.max(0.06, Number((baseIV + skewFactor * 1.08 + smileFactor).toFixed(4)));

    // BSM calculations
    const callBsm = calculateBSM(S, strike, T, callIV, 'call');
    const putBsm = calculateBSM(S, strike, T, putIV, 'put');

    // Spreads
    const callSpread = Math.max(0.02, Number((callBsm.price * 0.015 + 0.02).toFixed(2)));
    const putSpread = Math.max(0.02, Number((putBsm.price * 0.015 + 0.02).toFixed(2)));

    const callBid = Math.max(0.01, Number((callBsm.price - callSpread / 2).toFixed(2)));
    const callAsk = Number((callBsm.price + callSpread / 2).toFixed(2));

    const putBid = Math.max(0.01, Number((putBsm.price - putSpread / 2).toFixed(2)));
    const putAsk = Number((putBsm.price + putSpread / 2).toFixed(2));

    // Realistic Volume & Open Interest distribution (peak near ATM and round numbers)
    const distFromAtm = Math.abs(strike - roundedAtm) / S;
    const roundNumberBonus = strike % 5 === 0 ? 2.5 : strike % 1 === 0 ? 1.5 : 1.0;
    const baseVol = Math.max(20, Math.floor((12000 * roundNumberBonus) / (1 + distFromAtm * 35)));
    const baseOI = Math.max(80, Math.floor((34000 * roundNumberBonus) / (1 + distFromAtm * 25)));

    calls.push({
      strike,
      bid: callBid,
      ask: callAsk,
      last: callBsm.price,
      change: Number(((Math.random() - 0.45) * 0.35).toFixed(2)),
      volume: Math.floor(baseVol * (0.8 + Math.random() * 0.4)),
      openInterest: Math.floor(baseOI * (0.9 + Math.random() * 0.3)),
      iv: Number(callIV.toFixed(3)),
      delta: callBsm.greeks.delta,
      gamma: callBsm.greeks.gamma,
      theta: callBsm.greeks.theta,
      vega: callBsm.greeks.vega,
      rho: callBsm.greeks.rho,
      itm: S >= strike,
    });

    puts.push({
      strike,
      bid: putBid,
      ask: putAsk,
      last: putBsm.price,
      change: Number(((Math.random() - 0.52) * 0.35).toFixed(2)),
      volume: Math.floor(baseVol * (0.7 + Math.random() * 0.4)),
      openInterest: Math.floor(baseOI * (0.9 + Math.random() * 0.3)),
      iv: Number(putIV.toFixed(3)),
      delta: putBsm.greeks.delta,
      gamma: putBsm.greeks.gamma,
      theta: putBsm.greeks.theta,
      vega: putBsm.greeks.vega,
      rho: putBsm.greeks.rho,
      itm: S <= strike,
    });
  }

  const preset = EXPIRATION_PRESETS.find((p) => p.days === dteDays);

  return {
    expirationDate: dateStr,
    formattedDate,
    dte: dteDays,
    avgIV: Number(baseIV.toFixed(3)),
    month: monthName,
    monthYear,
    isQuadWitching: preset?.isQuadWitching || false,
    calls,
    puts,
  };
}

/**
 * Generates options chains across all standard expirations for a ticker
 */
export function generateAllOptionChainsForTicker(ticker: Ticker): ExpirationOptionChain[] {
  return EXPIRATION_PRESETS.map((preset) => generateOptionsChainForTicker(ticker, preset.days));
}

