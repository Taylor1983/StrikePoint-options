// Helper functions for G20 Yield Curves
export function getCountryYieldCurve(countryId: string): G20CountryYieldCurve {
  return G20_YIELD_CURVES.find((c) => c.id.toUpperCase() === countryId.toUpperCase()) || G20_YIELD_CURVES[0];
}

export function calculateSovereignSpread(
  countryAId: string,
  countryBId: string,
  tenor: string = '10Y'
): { spreadBps: number; tenor: string; aYield: number; bYield: number } {
  const curveA = getCountryYieldCurve(countryAId);
  const curveB = getCountryYieldCurve(countryBId);

  const ptA = curveA.points.find((p) => p.tenor === tenor) || curveA.points[curveA.points.length - 1];
  const ptB = curveB.points.find((p) => p.tenor === tenor) || curveB.points[curveB.points.length - 1];

  const spreadBps = Math.round((ptA.yield - ptB.yield) * 100);
  return {
    spreadBps,
    tenor,
    aYield: ptA.yield,
    bYield: ptB.yield,
  };
}
