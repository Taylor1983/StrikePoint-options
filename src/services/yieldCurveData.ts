export interface YieldCurvePoint {
  maturity: string; // "1M", "2M", "3M", "6M", "1Y", "2Y", "3Y", "5Y", "7Y", "10Y", "20Y", "30Y"
  years: number;    // e.g. 0.083, 0.167, 0.25, 0.5, 1, 2, 3, 5, 7, 10, 20, 30
  currentYield: number; // in %
  oneMonthAgoYield: number; // in %
  oneYearAgoYield: number; // in %
  change1M: number; // in bps
  change1Y: number; // in bps
}

export interface YieldCurveSpread {
  pair: string; // e.g. "2s10s", "3m10s", "5s30s"
  name: string;
  spreadBps: number; // 10Y - 2Y in basis points
  status: 'INVERTED' | 'FLAT' | 'NORMAL' | 'STEEPENING';
  significance: string;
}

export interface SovereignTenorPoint {
  tenor: string; // "1M", "3M", "6M", "1Y", "2Y", "3Y", "5Y", "7Y", "10Y", "20Y", "30Y"
  years: number;
  yield: number; // in %
  change1D: number; // bps
  change1M: number; // bps
  change1Y: number; // bps
}

export type YieldCurveShape = 'NORMAL' | 'INVERTED' | 'FLAT' | 'HUMPED' | 'STEEP';

export interface G20CountryYieldCurve {
  id: string; // "US", "DE", "JP", etc.
  country: string;
  flag: string;
  sovereignBondName: string;
  currency: string;
  currencySymbol: string;
  region: 'Americas' | 'Europe' | 'Asia-Pacific' | 'Emerging Markets' | 'G7';
  isG7: boolean;
  centralBank: string;
  policyRate: number; // in %
  cpiInflation: number; // in % YoY
  creditRating: string; // S&P / Moody's sovereign benchmark
  cds5YSpread: number; // in bps
  color: string; // Primary curve stroke color
  points: SovereignTenorPoint[];
  yield2Y: number;
  yield10Y: number;
  yield30Y: number;
  spread2s10s: number; // bps (10Y - 2Y)
  spread3m10s: number; // bps (10Y - 3M)
  spread5s30s: number; // bps (30Y - 5Y)
  realYield10Y: number; // 10Y - CPI (%)
  spreadVsUS10Y: number; // Country 10Y - US 10Y in bps
  spreadVsBund10Y: number; // Country 10Y - German 10Y in bps
  curveShape: YieldCurveShape;
  recessionProbability: number; // %
  lastUpdated: string;
  summary: string;
  monetaryStance: 'HAWKISH' | 'NEUTRAL' | 'DOVISH' | 'EMERGENCY_TIGHTENING' | 'EASING';
}

